// Downloads each item's lead image from its Wikipedia source page into
// games/timeline/images/ and regenerates games/timeline/data/images.js.
// An existing images/<id>.* file is kept, so hand-picked replacements survive a re-run.
import { readdir, writeFile, mkdir } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { items } from '../games/timeline/data/items.js';

const root = new URL('..', import.meta.url).pathname;
const imagesDir = join(root, 'games/timeline/images');
const manifestPath = join(root, 'games/timeline/data/images.js');
const headers = { 'User-Agent': 'nscoder-games-timeline/1.0 (local meetup game)' };
const THUMB_WIDTH = 800;

const titleOf = (source) => {
  const url = new URL(source);
  return url.hostname.endsWith('wikipedia.org') && url.pathname.startsWith('/wiki/')
    ? decodeURIComponent(url.pathname.slice('/wiki/'.length))
    : null;
};

const thumbnailUrl = async (title) => {
  const api = new URL('https://en.wikipedia.org/w/api.php');
  api.search = new URLSearchParams({
    action: 'query', format: 'json', redirects: '1', prop: 'pageimages',
    piprop: 'thumbnail', pithumbsize: String(THUMB_WIDTH), pilicense: 'any', titles: title,
  });
  const response = await fetch(api, { headers });
  const pages = Object.values((await response.json()).query?.pages ?? {});
  return pages[0]?.thumbnail?.source ?? null;
};

const download = async (item) => {
  const title = titleOf(item.source);
  const url = title && await thumbnailUrl(title);
  if (!url) return { id: item.id, status: 'no image' };

  const response = await fetch(url, { headers });
  if (!response.ok) return { id: item.id, status: `http ${response.status}` };

  const extension = extname(new URL(url).pathname).toLowerCase() || '.jpg';
  await writeFile(join(imagesDir, `${item.id}${extension}`), Buffer.from(await response.arrayBuffer()));
  return { id: item.id, status: 'downloaded' };
};

const existingFiles = async () =>
  Object.fromEntries((await readdir(imagesDir))
    .filter((file) => !file.startsWith('.'))
    .map((file) => [file.slice(0, -extname(file).length), file]));

const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

await mkdir(imagesDir, { recursive: true });
const already = await existingFiles();
const results = [];

// Sequential with a pause: Wikimedia asks automated clients to keep request rates low.
for (const item of items.filter(({ id }) => !already[id])) {
  results.push(await download(item).catch((error) => ({ id: item.id, status: error.message })));
  await pause(150);
}

const files = await existingFiles();
const known = items.filter(({ id }) => files[id]);
const entries = known.map(({ id }) => `  '${id}': '${files[id]}',`).join('\n');

await writeFile(manifestPath, `// Generated by scripts/fetch-images.mjs. Maps item id to a file in games/timeline/images/.
export const imageFiles = {
${entries}
};

export const imagePath = (id) => (imageFiles[id] ? \`images/\${imageFiles[id]}\` : null);
`);

const failed = results.filter(({ status }) => status !== 'downloaded');
console.log(`${known.length} of ${items.length} items have an image.`);
failed.forEach(({ id, status }) => console.log(`  missing ${id}: ${status}`));
